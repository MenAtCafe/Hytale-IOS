#!/usr/bin/env python3
"""
emit_switch.py - generate HytaleGL_GetProcAddress's dispatch table.

The hand-written switch declares each @convention(c) type by hand; a typo there
compiles and then corrupts the stack at call time. This reads the authoritative
Swift declarations in HytaleGL.swift and emits the cases, so the C signature is
declared exactly once.

  --verify   compare generated cases against the hand-written ones, exit 1 on drift

Usage:
  python3 harness/gen/emit_switch.py --verify
  python3 harness/gen/emit_switch.py -o harness/out/GLProcSwitch.generated.swift
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
SRC = REPO / "gate4/HytaleGL.swift"

DECL_RE = re.compile(
    r'@_cdecl\("([A-Za-z_][A-Za-z0-9_]*)"\)\s*'
    r"(?:@[A-Za-z_][A-Za-z0-9_]*(?:\([^)]*\))?\s*)*"
    r"public\s+func\s+([A-Za-z_][A-Za-z0-9_]*)\s*\((.*?)\)\s*"
    r"(?:->\s*([^{]+?))?\s*\{",
    re.S,
)

CASE_RE = re.compile(
    r'case\s+"(gl[A-Za-z0-9_]+)"\s*:\s*return\s+ptr\(\s*([A-Za-z0-9_]+)\s*'
    r"as\s+@convention\(c\)\s*\((.*?)\)\s*->\s*([^)]+?)\s*\)"
)

IDENT_RE = re.compile(r"^(.*?)([A-Za-z_][A-Za-z0-9_]*)$")


def split_params(s: str) -> list[str]:
    out: list[str] = []
    depth = 0
    cur: list[str] = []
    for ch in s:
        if ch in "<([":
            depth += 1
        elif ch in ">)]":
            depth = max(0, depth - 1)
        if ch == "," and depth == 0:
            out.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
    if "".join(cur).strip():
        out.append("".join(cur))
    return [p.strip() for p in out if p.strip()]


def swift_type(param: str) -> str:
    if ":" not in param:
        raise ValueError(f"unparsable parameter: {param!r}")
    return " ".join(param.split(":", 1)[1].split())


def parse_declarations(path: Path) -> dict[str, tuple[str, str]]:
    text = path.read_text()
    decls: dict[str, tuple[str, str]] = {}
    for m in DECL_RE.finditer(text):
        cname, ident, params, ret = m.group(1), m.group(2), m.group(3), m.group(4)
        if not cname.startswith("gl"):
            continue
        types = [swift_type(p) for p in split_params(params)]
        sig = "(" + ", ".join(types) + ")"
        decls[cname] = (ident, sig + " -> " + (" ".join((ret or "Void").split())))
    return decls


def parse_existing(path: Path) -> dict[str, tuple[str, str]]:
    text = path.read_text()
    found = {}
    for m in CASE_RE.finditer(text):
        cname, ident, params, ret = m.group(1), m.group(2), m.group(3), m.group(4)
        sig = "(" + ", ".join(" ".join(p.split()) for p in split_params(params)) + ")"
        found[cname] = (ident, sig + " -> " + " ".join(ret.split()))
    return found


def emit(decls: dict[str, tuple[str, str]]) -> str:
    lines = [
        "// GENERATED by harness/gen/emit_switch.py - do not edit.",
        "// Source of truth: the @_cdecl declarations in gate4/HytaleGL.swift.",
        "",
        "import Foundation",
        "import simd",
        "",
        "@inline(__always)",
        "private func hytalePtr<T>(_ f: T) -> UnsafeMutableRawPointer {",
        "    unsafeBitCast(f, to: UnsafeMutableRawPointer.self)",
        "}",
        "",
        "/// Resolve a GL entry point to its C ABI implementation, or nil.",
        "func hytaleGL_resolve(_ s: String) -> UnsafeMutableRawPointer? {",
        "    switch s {",
    ]
    for cname in sorted(decls):
        ident, sig = decls[cname]
        lines.append(f'    case "{cname}": return hytalePtr({ident} as @convention(c) {sig})')
    lines += ["    default: return nil", "    }", "}", ""]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--out", default=str(REPO / "harness/out/GLProcSwitch.generated.swift"))
    ap.add_argument("--verify", action="store_true")
    args = ap.parse_args()

    decls = parse_declarations(SRC)
    if not decls:
        sys.exit("no @_cdecl declarations found - did HytaleGL.swift move?")

    if args.verify:
        existing = parse_existing(SRC)
        missing = sorted(set(existing) - set(decls))
        added = sorted(set(decls) - set(existing))
        mismatched = sorted(
            n for n in set(existing) & set(decls) if existing[n][1] != decls[n][1]
        )
        print(f"{len(decls)} declarations, {len(existing)} hand-written cases")
        for n in missing:
            print(f"  MISSING decl: {n}")
        for n in added:
            print(f"  UNWIRED decl: {n}")
        for n in mismatched:
            print(f"  MISMATCH {n}\n    hand: {existing[n][1]}\n    gen : {decls[n][1]}")
        if missing or mismatched:
            sys.exit(1)
        print("ok: every hand-written case matches its declaration")
        return

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(emit(decls))
    print(f"wrote {out.relative_to(REPO)}: {len(decls)} cases")


if __name__ == "__main__":
    main()
